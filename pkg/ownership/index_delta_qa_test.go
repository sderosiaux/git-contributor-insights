// This fixture deliberately changes graph ancestry, paths, blob classification,
// and attribution independently. Native Git blame is the oracle, not a second
// invocation of the index's delta builder.
func TestDeltaQAMixedLegacyDAGReconstructionAndRestart(t *testing.T) {
	ctx := context.Background()
	repo := validationRepository(t)
	expected := map[string][]string{}
	excluded := map[string]string{}
	commit := func(name, date, subject string, paths ...string) string {
		sha := validationCommit(t, repo, name, strings.ToLower(name)+"@qa.test", date, date, subject)
		expected[sha] = paths
		return sha
	}
	validationWrite(t, repo, "main.go", "original\nstable\n")
	validationWrite(t, repo, "untouched.go", "steady\n")
	validationWrite(t, repo, "toggle.txt", "human authored\n")
	validationWrite(t, repo, "legacy-generated.go", "// Code generated by fixture. DO NOT EDIT.\nold generated source\n")
	root := commit("Root", "2020-01-01T12:00:00Z", "Root", "main.go", "toggle.txt", "untouched.go")
	excluded[root] = "generated header"
	validationGit(t, repo, nil, "checkout", "-q", "-b", "side")
	validationWrite(t, repo, "main.go", "side\nstable\n")
	validationWrite(t, repo, "transient.go", "branch-only line\n")
	excluded[commit("Side", "2020-01-02T12:00:00Z", "Side edit", "main.go", "toggle.txt", "transient.go", "untouched.go")] = "generated header"
	validationWrite(t, repo, "main.go", "original\nstable\n")
	excluded[commit("Reverter", "2020-01-02T12:00:00Z", "Same-time restore of original blob", "main.go", "toggle.txt", "transient.go", "untouched.go")] = "generated header"
	validationWrite(t, repo, "main.go", "side\nstable\n")
	sideTip := commit("SideAgain", "2020-01-03T12:00:00Z", "Restore side blob with new attribution", "main.go", "toggle.txt", "transient.go", "untouched.go")
	excluded[sideTip] = "generated header"
	validationGit(t, repo, nil, "checkout", "-q", "main")
	validationGit(t, repo, nil, "rm", "-q", "legacy-generated.go")
	validationWrite(t, repo, "main.go", "main\nstable\n")
	commit("Main", "2020-01-04T12:00:00Z", "Divergent main edit", "main.go", "toggle.txt", "untouched.go")
	// Build a genuine two-parent merge with an explicitly resolved tree.
	validationGit(t, repo, []string{"GIT_COMMITTER_NAME=Merger", "GIT_COMMITTER_EMAIL=merger@qa.test"}, "merge", "-q", "--no-ff", "--no-commit", "-s", "ours", "side")
	validationWrite(t, repo, "main.go", "side\nmain\nstable\n")
	validationWrite(t, repo, "transient.go", "branch-only line\n")
	commit("Merger", "2020-01-05T12:00:00Z", "Resolve both parents", "main.go", "toggle.txt", "transient.go", "untouched.go")
	validationGit(t, repo, nil, "mv", "main.go", "moved.go")
	commit("Renamer", "2020-01-06T12:00:00Z", "Rename without changing source", "moved.go", "toggle.txt", "transient.go", "untouched.go")
	validationGit(t, repo, nil, "rm", "-q", "moved.go", "transient.go")
	commit("Deleter", "2020-01-07T12:00:00Z", "Delete attributed paths", "toggle.txt", "untouched.go")
	validationWrite(t, repo, "moved.go", "original\nstable\n")
	commit("Reborn", "2020-01-08T12:00:00Z", "Re-add earlier blob at deleted path", "moved.go", "toggle.txt", "untouched.go")
	validationWrite(t, repo, "toggle.txt", "binary\x00payload\n")
	binary := commit("Binary", "2020-01-09T12:00:00Z", "Included text becomes binary", "moved.go", "untouched.go")
	excluded[binary] = "binary"
	validationWrite(t, repo, "toggle.txt", "// Code generated by fixture. DO NOT EDIT.\ngenerated\n")
	generated := commit("Generator", "2020-01-10T12:00:00Z", "Change exclusion reason", "moved.go", "untouched.go")
	excluded[generated] = "generated header"
	validationWrite(t, repo, "toggle.txt", "human authored again\n")
	commit("Human", "2020-01-11T12:00:00Z", "Excluded path becomes source again", "moved.go", "toggle.txt", "untouched.go")

	dbPath := filepath.Join(t.TempDir(), "index.sqlite")
	index, err := OpenIndex(ctx, repo, Options{}, dbPath)
	if err != nil {
		t.Fatal(err)
	}
	if err := index.persistMetadata(ctx); err != nil {
		t.Fatal(err)
	}
	rootRevision := index.allRevisions[0]
	if rootRevision.sha != root {
		t.Fatal("fixture root must be the first topological revision")
	}
	legacy, err := index.session.engine.snapshotWithActivity(cutoff{date: rootRevision.date, sha: root}, 90, false)
	if err != nil {
		t.Fatal(err)
	}
	if err := index.persistRevision(ctx, legacy, rootRevision.date); err != nil {
		t.Fatal(err)
	}
	var legacyBlob []byte
	if err := index.db.QueryRow("SELECT snapshot FROM revisions WHERE fingerprint=? AND sha=?", index.fingerprint, root).Scan(&legacyBlob); err != nil {
		t.Fatal(err)
	}
	if err := index.Close(); err != nil {
		t.Fatal(err)
	}
	index, err = OpenIndex(ctx, repo, Options{}, dbPath)
	if err != nil {
		t.Fatal(err)
	}
	index.checkpointEvery = 2
	if index.Status().Completed != 1 {
		t.Fatal("legacy checkpoint was not reused")
	}
	// Simulate a process stopping after several committed deltas, including a
	// side-history checkpoint. Resume must retain these exact saved documents.
	saved := map[string][]byte{root: legacyBlob}
	for _, revision := range index.allRevisions[1:5] {
		state, delta, err := index.buildRevisionState(ctx, revision)
		if err != nil {
			t.Fatal(err)
		}
		if err := index.persistRevisionState(ctx, revision, state, delta); err != nil {
			t.Fatal(err)
		}
		var payload []byte
		if err := index.db.QueryRow("SELECT snapshot FROM revisions WHERE fingerprint=? AND sha=?", index.fingerprint, revision.sha).Scan(&payload); err != nil {
			t.Fatal(err)
		}
		saved[revision.sha] = payload
	}
	if err := index.Close(); err != nil {
		t.Fatal(err)
	}
	index, err = OpenIndex(ctx, repo, Options{}, dbPath)
	if err != nil {
		t.Fatal(err)
	}
	index.checkpointEvery = 2
	if index.Status().Completed != len(saved) {
		t.Fatalf("partial delta checkpoints were not resumed: %+v", index.Status())
	}
	if err := index.Run(ctx); err != nil {
		t.Fatal(err)
	}
	for sha, payload := range saved {
		var restored []byte
		if err := index.db.QueryRow("SELECT snapshot FROM revisions WHERE fingerprint=? AND sha=?", index.fingerprint, sha).Scan(&restored); err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(payload, restored) {
			t.Fatalf("resume rewrote committed state %s", sha)
		}
	}
	var actualBlob []byte
	if err := index.db.QueryRow("SELECT snapshot FROM revisions WHERE fingerprint=? AND sha=?", index.fingerprint, root).Scan(&actualBlob); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(legacyBlob, actualBlob) {
		t.Fatal("migration rewrote the legacy ownership checkpoint")
	}
	var checkpoints, deltas, maxDepth int
	if err := index.db.QueryRow("SELECT COALESCE(SUM(checkpoint),0), COALESCE(SUM(CASE WHEN checkpoint=0 THEN 1 ELSE 0 END),0), COALESCE(MAX(depth),0) FROM revision_deltas WHERE fingerprint=?", index.fingerprint).Scan(&checkpoints, &deltas, &maxDepth); err != nil {
		t.Fatal(err)
	}
	if checkpoints == 0 || deltas == 0 || maxDepth > 2 {
		t.Fatalf("fixture did not exercise bounded mixed reconstruction: checkpoints=%d deltas=%d depth=%d", checkpoints, deltas, maxDepth)
	}
	check := func(index *Index, reverse bool) {
		t.Helper()
		if index.Status().Completed != len(expected) || index.Status().Total != len(expected) {
			t.Fatalf("missing graph states: %+v", index.Status())
		}
		for n := range index.allRevisions {
			position := n
			if reverse {
				position = len(index.allRevisions) - 1 - n
			}
			revision := index.allRevisions[position]
			// Read-time identity grouping and activity must not mutate cached stock.
			if _, err := index.Revision(ctx, revision.sha); err != nil {
				t.Fatal(err)
			}
			snapshot, err := index.readSnapshot(ctx, revision.sha, revision.date)
			if err != nil {
				t.Fatal(err)
			}
			deltaQAAssertNativeSnapshot(t, index, repo, snapshot, expected[revision.sha], excluded[revision.sha])
		}
	}
	check(index, false)
	if err := index.Close(); err != nil {
		t.Fatal(err)
	}
	index, err = OpenIndex(ctx, repo, Options{}, dbPath)
	if err != nil {
		t.Fatal(err)
	}
	defer index.Close()
	if index.Status().State != "ready" {
		t.Fatalf("complete delta index did not reopen ready: %+v", index.Status())
	}
	// Warm reconstruction caches concurrently, exercising their shared read path.
	var workers sync.WaitGroup
	errors := make(chan error, len(index.allRevisions))
	for _, revision := range index.allRevisions {
		workers.Add(1)
		go func(revision indexedRevision) {
			defer workers.Done()
			_, err := index.readSnapshot(ctx, revision.sha, revision.date)
			errors <- err
		}(revision)
	}
	workers.Wait()
	close(errors)
	for err := range errors {
		if err != nil {
			t.Fatal(err)
		}
	}
	check(index, true)
	last := index.allRevisions[len(index.allRevisions)-1]
	for _, tip := range []string{last.sha, sideTip} {
		for _, scope := range []string{"", "moved.go", "toggle.txt"} {
			assertCompactEquivalent(t, index, "", "", scope, tip)
			dataset, err := index.QueryHistory(ctx, "", "", scope, tip)
			if err != nil {
				t.Fatal(err)
			}
			for _, point := range dataset.Series {
				if point.Kind != "revision" {
					continue
				}
				snapshot, err := index.readSnapshot(ctx, point.Revision, last.date)
				if err != nil {
					t.Fatal(err)
				}
				want, got := map[string]int{}, map[string]int{}
				lines := 0
				for _, file := range snapshot.Files {
					if scope != "" && file.Path != scope {
						continue
					}
					lines += file.Lines
					for _, value := range file.Contributions {
						if value.Lines > 0 {
							want[value.PersonID+"\x00"+value.OrganizationID] += value.Lines
						}
					}
				}
				for _, value := range point.Contributions {
					if value.Lines > 0 {
						got[value.PersonID+"\x00"+value.OrganizationID] += value.Lines
					}
				}
				if point.Lines != lines || !reflect.DeepEqual(got, want) {
					t.Fatalf("aggregate delta diverges at %s scope %q: lines=%d/%d actors=%v/%v", point.Revision, scope, point.Lines, lines, got, want)
				}
			}
		}
	}
	mutated, err := index.readSnapshot(ctx, last.sha, last.date)
	if err != nil {
		t.Fatal(err)
	}
	mutated.Files[0].Lines = 999999
	mutated.Files[0].Contributions[0].Lines = 999999
	mutated.Files[0].Contributions[0].Evidence[0].SHA = "must-not-poison-cache"
	again, err := index.readSnapshot(ctx, last.sha, last.date)
	if err != nil {
		t.Fatal(err)
	}
	deltaQAAssertNativeSnapshot(t, index, repo, again, expected[last.sha], excluded[last.sha])
}

func deltaQAAssertNativeSnapshot(t *testing.T, index *Index, repo string, snapshot Snapshot, paths []string, exclusion string) {
	t.Helper()
	actualPaths := make([]string, 0, len(snapshot.Files))
	for _, file := range snapshot.Files {
		actualPaths = append(actualPaths, file.Path)
	}
	wantPaths := append([]string{}, paths...)
	sort.Strings(actualPaths)
	sort.Strings(wantPaths)
	if !reflect.DeepEqual(actualPaths, wantPaths) {
		t.Fatalf("paths at %s: got %v want %v", snapshot.Revision, actualPaths, wantPaths)
	}
	wantExclusions := map[string]int{}
	if exclusion != "" {
		wantExclusions[exclusion] = 1
	}
	if !reflect.DeepEqual(snapshot.Exclusions, wantExclusions) || snapshot.ExcludedFiles != len(wantExclusions) {
		t.Fatalf("classification at %s: got %v / %d want %v", snapshot.Revision, snapshot.Exclusions, snapshot.ExcludedFiles, wantExclusions)
	}
	for _, file := range snapshot.Files {
		wantCounts, wantEvidence := map[string]int{}, map[string]bool{}
		sha, originalPath, email := "", file.Path, ""
		output := validationGit(t, repo, nil, "blame", "--no-textconv", "--line-porcelain", snapshot.Revision, "--", file.Path)
		for _, line := range strings.Split(output, "\n") {
			fields := strings.Fields(line)
			if len(fields) >= 3 && len(fields[0]) == 40 {
				if _, err := strconv.Atoi(fields[1]); err == nil {
					sha, originalPath = fields[0], file.Path
				}
			}
			if strings.HasPrefix(line, "author-mail ") {
				email = strings.Trim(strings.TrimPrefix(line, "author-mail "), "<>")
			}
			if strings.HasPrefix(line, "filename ") {
				originalPath = strings.TrimPrefix(line, "filename ")
				if strings.HasPrefix(originalPath, "\"") {
					decoded, err := strconv.Unquote(originalPath)
					if err != nil {
						t.Fatal(err)
					}
					originalPath = decoded
				}
			}
			if strings.HasPrefix(line, "\t") {
				wantCounts[email]++
				wantEvidence[sha+"\x00"+originalPath] = true
			}
		}
		actualCounts, actualEvidence := map[string]int{}, map[string]bool{}
		lines := 0
		for _, contribution := range file.Contributions {
			person, exists := index.session.engine.identities[contribution.PersonID]
			if !exists {
				t.Fatalf("unknown stored identity %s", contribution.PersonID)
			}
			actualCounts[person.Email] += contribution.Lines
			lines += contribution.Lines
			if contribution.ChangedLines != 0 {
				t.Fatal("read-time activity contaminated immutable ownership stock")
			}
			for _, evidence := range contribution.Evidence {
				if evidence.Kind != "ownership" {
					t.Fatalf("non-ownership evidence in stock: %+v", evidence)
				}
				actualEvidence[evidence.SHA+"\x00"+evidence.Path] = true
			}
		}
		if !reflect.DeepEqual(actualCounts, wantCounts) || file.Lines != lines {
			t.Fatalf("native attribution at %s:%s: stored=%v lines=%d native=%v", snapshot.Revision, file.Path, actualCounts, file.Lines, wantCounts)
		}
		if !reflect.DeepEqual(actualEvidence, wantEvidence) {
			t.Fatalf("native evidence at %s:%s: stored=%s native=%s", snapshot.Revision, file.Path, fmt.Sprint(actualEvidence), fmt.Sprint(wantEvidence))
		}
	}
}
