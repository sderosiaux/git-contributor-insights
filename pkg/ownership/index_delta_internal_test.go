func TestIndexDeltaFileDirectoryReplacementUsesExactPaths(t *testing.T) {
	repo := validationRepository(t)
	validationWrite(t, repo, "nested", "file before directory\n")
	validationCommit(t, repo, "First", "first@test.invalid", "2020-01-01T12:00:00Z", "2020-01-01T12:00:00Z", "File")
	validationGit(t, repo, nil, "rm", "nested")
	validationWrite(t, repo, "nested/a.go", "first child\n")
	validationWrite(t, repo, "nested/b.go", "second child\n")
	middle := validationCommit(t, repo, "Second", "second@test.invalid", "2020-01-02T12:00:00Z", "2020-01-02T12:00:00Z", "Directory")
	validationGit(t, repo, nil, "rm", "-r", "nested")
	validationWrite(t, repo, "nested", "file again\n")
	last := validationCommit(t, repo, "Third", "third@test.invalid", "2020-01-03T12:00:00Z", "2020-01-03T12:00:00Z", "File again")
	index, err := OpenIndex(context.Background(), repo, Options{}, filepath.Join(t.TempDir(), "index.sqlite"))
	if err != nil {
		t.Fatal(err)
	}
	defer index.Close()
	if err := index.Run(context.Background()); err != nil {
		t.Fatal(err)
	}
	for sha, want := range map[string]int{middle: 2, last: 1} {
		state, err := index.readRevisionState(context.Background(), sha)
		if err != nil {
			t.Fatal(err)
		}
		if state.lines != want || len(state.files) != want {
			t.Fatalf("%s: lines=%d files=%d want %d", sha, state.lines, len(state.files), want)
		}
		data, err := index.QueryHistory(context.Background(), "", "", "nested", sha)
		if err != nil {
			t.Fatal(err)
		}
		if data.Series[len(data.Series)-1].Lines != want {
			t.Fatal("scope line total duplicated prefix-selected file")
		}
	}
}

func TestIndexMetadataBatchesResumeBeforeHeadMarker(t *testing.T) {
	ctx := context.Background()
	repo := validationRepository(t)
	for n := 0; n < 258; n++ {
		validationWrite(t, repo, fmt.Sprintf("generated/%03d.txt", n), fmt.Sprintf("// Code generated by fixture. DO NOT EDIT.\n%d\n", n))
	}
	validationWrite(t, repo, "source.go", "human\n")
	validationCommit(t, repo, "Alice", "alice@test.invalid", "2020-01-01T12:00:00Z", "2020-01-01T12:00:00Z", "Batch fixture")
	dbPath := filepath.Join(t.TempDir(), "index.sqlite")
	index, err := OpenIndex(ctx, repo, Options{}, dbPath)
	if err != nil {
		t.Fatal(err)
	}
	if err := index.persistCommitMetadata(ctx); err != nil {
		t.Fatal(err)
	}
	trees, err := index.activityTrees()
	if err != nil {
		t.Fatal(err)
	}
	entries := index.session.engine.activity[:64]
	files := make([]treeFile, len(entries))
	for n, entry := range entries {
		files[n] = trees[entry.sha+"\x00"+entry.path]
	}
	if err := index.session.engine.classifyBatch(files); err != nil {
		t.Fatal(err)
	}
	reasons := make([]string, len(files))
	for n, file := range files {
		reasons[n], err = index.session.engine.classify(file)
		if err != nil {
			t.Fatal(err)
		}
	}
	if err := index.persistActivityBatch(ctx, entries, reasons); err != nil {
		t.Fatal(err)
	}
	var count int
	if err := index.db.QueryRow("SELECT COUNT(*) FROM indexed_heads").Scan(&count); err != nil || count != 0 {
		t.Fatalf("incomplete metadata marked ready: %d %v", count, err)
	}
	if err := index.Close(); err != nil {
		t.Fatal(err)
	}
	index, err = OpenIndex(ctx, repo, Options{}, dbPath)
	if err != nil {
		t.Fatal(err)
	}
	defer index.Close()
	if err := index.Run(ctx); err != nil {
		t.Fatal(err)
	}
	if err := index.db.QueryRow("SELECT COUNT(*) FROM activity").Scan(&count); err != nil || count != 259 {
		t.Fatalf("resumed metadata rows=%d err=%v", count, err)
	}
	status := index.Status()
	if status.PhaseCompleted != 259 || status.PhaseTotal != 259 {
		t.Fatalf("metadata progress=%+v", status)
	}
	state, err := index.readRevisionState(ctx, status.Head)
	if err != nil {
		t.Fatal(err)
	}
	if state.lines != 1 || len(state.files) != 1 || state.exclusions["generated header"] != 258 {
		t.Fatalf("batch classification mismatch: lines=%d files=%d exclusions=%v", state.lines, len(state.files), state.exclusions)
	}
}
